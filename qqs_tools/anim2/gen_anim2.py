#!/usr/bin/env python3
"""
QQS-Pro: the probe (G29 / G33 ...) and PID animations from George's drawings (src/*.png).

  python3 qqs_tools/anim2/gen_anim2.py      -> Marlin/src/lcd/tft/qqs/qqs_anim2_data.{h,cpp}, anim2_preview.png

Each animation = a 160 x 120 base picture (2 bpp) + "slots": fixed rectangles that do not overlap,
each with a few pre-rendered states (2 bpp patches). A slot's rectangle is the union of everything
that changes in it over all its states (with the other slots in their default state).
The firmware draws the base once, then only the slots whose state changed (fill the rect, draw the patch:
level 0 is transparent in Marlin's greyscale images).
Parts are composited at the final resolution with a 1 px black outline (George 2026-11-25), order
back to front: body, ahoge, left hand, sextant, right hand / rod, hand.
"""
import os, sys
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import g29, pid

OUT = os.path.join(HERE, '..', '..', 'Marlin', 'src', 'lcd', 'tft', 'qqs')

def lv2(f):                          # 0..1 -> 2 bpp levels 0..3
    return np.round(np.clip(f, 0, 1) * 3).astype(np.uint8)

def pack(lv, bpp=2):
    h, w = lv.shape; per = 8 // bpp; out = bytearray()
    for r in range(h):
        row = list(lv[r]) + [0] * ((-w) % per)
        for i in range(0, len(row), per):
            v = 0
            for k in range(per): v = (v << bpp) | int(row[i + k])
            out.append(v)
    return out

def build(name, base_fn, slots):
    """slots: list of (slot name, [state kwargs...], default index)"""
    defaults = {}
    for sname, states, d in slots: defaults.update(states[d])
    base = lv2(base_fn(**defaults))
    out = {'base': base, 'slots': []}
    rects, masks = [], []
    for sname, states, d in slots:
        imgs = []
        for st in states:
            kw = dict(defaults); kw.update(st)
            imgs.append(lv2(base_fn(**kw)))
        diff = np.zeros(base.shape, bool)
        for im in imgs: diff |= im != base
        ys, xs = np.nonzero(diff)
        if not len(xs): raise SystemExit(f'{name}.{sname}: no change')
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
        rects.append((x0, y0, x1, y1)); masks.append(diff)
        out['slots'].append([sname, (int(x0), int(y0)), [im[y0:y1, x0:x1] for im in imgs], 0, d])
    # Overlapping rects are allowed when only the later slot changes pixels inside the overlap. Each patch
    # holds the other slot's default content there; for the earlier slot that equals its current content
    # (it never changes there), so: earlier redraws -> also redraw the later one ('after' bit mask);
    # later redraws alone -> fine. The firmware draws dirty slots in index order.
    n = len(rects)
    for i in range(n):
        for j in range(i + 1, n):
            a, b = rects[i], rects[j]
            ox0, oy0, ox1, oy1 = max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3])
            if ox0 >= ox1 or oy0 >= oy1: continue
            si, sj = out['slots'][i][0], out['slots'][j][0]
            if masks[i][oy0:oy1, ox0:ox1].any():
                raise SystemExit(f'{name}: {si} changes pixels where it overlaps {sj}; list {si} after {sj} or split it')
            out['slots'][i][3] |= 1 << j
            print(f'  {name}: {si} overlaps {sj} ({ox1-ox0}x{oy1-oy0}); {sj} is redrawn after {si}')
    return out


G29_SLOTS = [  # arms first: the ahoge owns the few overlapping pixels
    ('arms',  [dict(head='open', lift=0.0), dict(head='open', lift=1/3), dict(head='open', lift=2/3),
               dict(head='open', lift=1.0), dict(head='wink', lift=1.0)], 0),
    ('ahoge', [dict(ahoge=-4.0), dict(ahoge=0.0), dict(ahoge=4.0)], 1),
    ('star',  [dict(tw=(1.0, 1, 1, 1)), dict(tw=(0.75, 1, 1, 1)), dict(tw=(1.3, 1, 1, 1)), dict(tw=(1.7, 1, 1, 1))], 0),
]
PID_SLOTS = [
    ('hand',  [dict(ang=a) for a in (-6.0, -3.0, 0.0, 3.0, 6.0)], 2),
    ('flame', [dict(flame=None), dict(flame=0.45), dict(flame=0.7), dict(flame=1.0),
               dict(flame=0.7, flip=True), dict(flame=1.0, flip=True)], 0),
    ('steam', [dict(steam=None)] + [dict(steam=p) for p in (0.0, 0.25, 0.5, 0.75)], 0),
    ('star1', [dict(s1=s) for s in (0.8, 1.0, 1.15)], 1),
    ('star2', [dict(s2=s) for s in (0.8, 1.0, 1.15)], 1),
    ('ahoge', [dict(ahoge=a) for a in (-4.0, 0.0, 4.0)], 1),
]

def main():
    anims = {'g29': build('g29', g29.frame, G29_SLOTS), 'pid': build('pid', pid.frame, PID_SLOTS)}
    H = ['// Generated by qqs_tools/anim2/gen_anim2.py — do not edit.', '#pragma once', '#include "qqs_font.h"', '',
         'typedef struct { uint8_t x, y, n, d, after; const qqs_bitmap_t * const *f; } qqs_anim2_slot_t;   // d: state in the base picture; after: later slots to redraw too',
         'typedef struct { const qqs_bitmap_t *base; uint8_t nslots; const qqs_anim2_slot_t *slots; } qqs_anim2_t;', '']
    C = ['// Generated by qqs_tools/anim2/gen_anim2.py — do not edit.', '#include "qqs_anim2_data.h"', '']
    total = 0
    for an, a in anims.items():
        b = pack(a['base']); total += len(b)
        C.append(f'static const uint8_t {an}_base_d[] = {{ {",".join(str(v) for v in b)} }};')
        C.append(f'static const qqs_bitmap_t {an}_base = {{ 160, 120, 2, {an}_base_d }};')
        slot_lines = []
        for sname, (x, y), ims, after, dflt in a['slots']:
            names = []
            for k, im in enumerate(ims):
                d = pack(im); total += len(d)
                C.append(f'static const uint8_t {an}_{sname}{k}_d[] = {{ {",".join(str(v) for v in d)} }};')
                C.append(f'static const qqs_bitmap_t {an}_{sname}{k} = {{ {im.shape[1]}, {im.shape[0]}, 2, {an}_{sname}{k}_d }};')
                names.append(f'&{an}_{sname}{k}')
            C.append(f'static const qqs_bitmap_t * const {an}_{sname}_f[] = {{ {", ".join(names)} }};')
            slot_lines.append(f'  {{ {x}, {y}, {len(ims)}, {dflt}, 0x{after:02X}, {an}_{sname}_f }},   // {sname}')
            H.append(f'#define QQS_A2_{an.upper()}_{sname.upper()} {len(slot_lines) - 1}   // {len(ims)} states')
        C.append(f'static const qqs_anim2_slot_t {an}_slots[] = {{\n' + '\n'.join(slot_lines) + '\n};')
        C.append(f'const qqs_anim2_t qqs_anim2_{an} = {{ &{an}_base, {len(slot_lines)}, {an}_slots }};')
        H.append(f'extern const qqs_anim2_t qqs_anim2_{an};')
        C.append('')
    open(os.path.join(OUT, 'qqs_anim2_data.h'), 'w').write('\n'.join(H) + '\n')
    open(os.path.join(OUT, 'qqs_anim2_data.cpp'), 'w').write('\n'.join(C) + '\n')
    # preview: base + every slot state, x2
    OR = np.array([0xFF, 0x8C, 0x28]); BG = np.array([0x1A, 0x1A, 0x1A])
    def rgb(lv): f = lv[..., None] / 3.0; return (OR * f + BG * (1 - f)).astype(np.uint8)
    tiles = []
    for an, a in anims.items():
        for sname, (x, y), ims, _, _d in a['slots']:
            for im in ims:
                fr = a['base'].copy(); fr[y:y + im.shape[0], x:x + im.shape[1]] = im
                tiles.append(rgb(fr))
    cols = 6; rows = (len(tiles) + cols - 1) // cols
    sheet = np.zeros((rows * 124, cols * 164, 3), np.uint8) + 60
    for i, t in enumerate(tiles): sheet[(i // cols) * 124 + 2:(i // cols) * 124 + 122, (i % cols) * 164 + 2:(i % cols) * 164 + 162] = t
    Image.fromarray(sheet).resize((sheet.shape[1] * 2, sheet.shape[0] * 2), Image.NEAREST).save(os.path.join(HERE, 'anim2_preview.png'))
    for an, a in anims.items():
        print(an, 'slots', [(s, xy, len(ims), ims[0].shape, af, d) for s, xy, ims, af, d in a['slots']])
    print('total data', total, 'bytes')

if __name__ == '__main__':
    main()

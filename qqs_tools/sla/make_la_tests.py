#!/usr/bin/env python3
"""
QQS-Pro v3.2.9: test G-code for tuning Smooth LA on the delta (round bed, radius 130).

  python3 make_la_tests.py [outdir]

Writes
  LA0_AIR.gcode       air extrusion, no printing: which E speed / acceleration the stealthChop
                      extruder can do without skipping (mark the filament, net E is 0)
  LA1_K.gcode         K sweep, one value every 5 mm
  LA2_U.gcode         U (release tau) sweep, K from the top line (edit it)
  LA3_J.gcode         J (release K) sweep, K / U from the top line (edit them)

The towers: 40 x 40 mm single wall, 0.45 x 0.2, each edge = 10 mm slow, 20 mm fast, 10 mm slow,
so every edge has two speed changes besides the corners. With the right value the line has the
same width through the changes: too low K -> thin after speeding up / blob after slowing down,
too high -> the reverse. Each band starts with M117 (status line) and M118 (terminal).
"""
import math, os, sys

OUT = sys.argv[1] if len(sys.argv) > 1 else '.'
NOZZLE, BED = 210, 60            # PLA; change here for other filament
LW, LH = 0.45, 0.2
FIL_AREA = math.pi * 0.875 ** 2
E_PER_MM = LW * LH / FIL_AREA
SIDE = 40.0
SLOW, FAST = 25.0, 100.0         # mm/s
FIRST = 20.0                     # first layer mm/s
BAND = 5.0                       # mm per value
BASE = 1.0                       # mm before the first band (first value, not counted as a band)

def header(title, notes, setup_lines):
    g = [f'; QQS-Pro v3.2.9 Smooth LA test: {title}', '; generated by qqs_tools/sla/make_la_tests.py']
    g += ['; ' + n for n in notes]
    g += [f'M140 S{BED}', 'M104 S150', 'G28', f'M190 S{BED}', f'M109 S{NOZZLE}',
          'M83', 'G92 E0', 'M107']
    g += setup_lines
    # prime line along the front, inside the radius
    g += ['G1 Z5 F3000', 'G1 X-50 Y-75 F6000', f'G1 Z{LH + 0.05:.2f} F1200',
          f'G1 X50 Y-75 E{100 * E_PER_MM * 1.5:.3f} F1200', 'G1 Z1 F1200']
    return g

def footer(h):
    return ['M107', 'M104 S0', 'M140 S0', 'M83', 'G1 E-2 F1800', f'G1 Z{h + 15:.1f} F1200', 'G28',
            'M900 K0 ; leave LA off (M500 not sent: nothing is saved)', 'M84', 'M117 Test done']

def edge(x0, y0, x1, y1, f_slow, f_fast):
    """One edge: 1/4 slow, 1/2 fast, 1/4 slow."""
    out = []
    pts = [0.25, 0.75, 1.0]
    speeds = [f_slow, f_fast, f_slow]
    px, py = x0, y0
    for p, v in zip(pts, speeds):
        x, y = x0 + (x1 - x0) * p, y0 + (y1 - y0) * p
        d = math.hypot(x - px, y - py)
        out.append(f'G1 X{x:.3f} Y{y:.3f} E{d * E_PER_MM:.5f} F{v * 60:.0f}')
        px, py = x, y
    return out

def layer(z, first):
    s = SIDE / 2
    c = [(-s, -s), (s, -s), (s, s), (-s, s), (-s, -s)]
    out = [f'G1 Z{z:.2f} F1200']
    for (x0, y0), (x1, y1) in zip(c, c[1:]):
        out += edge(x0, y0, x1, y1, FIRST if first else SLOW, FIRST if first else FAST)
    return out

def tower(name, title, param, values, fixed_line, notes):
    h = BASE + BAND * len(values)
    g = header(title, notes, [fixed_line + '   ; <- fixed values for this tower: edit here', f'M900 {param}{values[0]}'])
    s = SIDE / 2
    g += [f'G1 X{-s:.3f} Y{-s:.3f} F6000', f'G1 Z{LH:.2f} F1200']
    z, band = LH, -1
    n = 0
    while z < h - 1e-6:
        b = min(int((z - BASE + 1e-6) // BAND), len(values) - 1) if z > BASE else -1
        if b != band and b >= 0:
            band = b
            v = values[b]
            g += [f'M900 {param}{v}', f'M117 {param}={v}  ({b * BAND + BASE:.0f}-{(b + 1) * BAND + BASE:.0f} mm)',
                  f'M118 band {b + 1}: {param}={v} from Z{z:.1f}']
        if n == 2: g.append('M106 S255')
        g += layer(z, n == 0)
        z = round(z + LH, 3); n += 1
    g += footer(h)
    with open(os.path.join(OUT, name), 'w', newline='\n') as f: f.write('\n'.join(g) + '\n')
    return h

def air_test():
    g = ['; QQS-Pro v3.2.9 air extrusion test for the stealthChop extruder (no printing)',
         '; Before: heat is done by this file. Lift nothing, print nothing: the nozzle stays at Z50.',
         '; 1. Put a pen mark on the filament where it enters the extruder (or on the Bowden coupler side).',
         '; 2. Each group pushes and pulls 4 mm 8 times (net 0). Watch / listen for clicks or stalls.',
         '; 3. After each group (2 s pause) the mark must be back at the same place. If it moved, that group skipped.',
         '; The planner limits (M201 E, M204 R, M203 E) are set per group and restored with M501 at the end.',
         f'M104 S{NOZZLE}', 'G28', 'G1 Z50 F3000', f'M109 S{NOZZLE}', 'M83', 'M203 E120',
         'G1 E5 F300 ; fill the nozzle', 'G4 S2']
    groups = [(10, 300), (20, 300), (30, 300), (20, 1000), (30, 1000), (40, 1000),
              (30, 3000), (40, 3000), (50, 3000), (40, 5000), (60, 5000)]
    for i, (v, a) in enumerate(groups, 1):
        g += [f'M117 Air {i}/{len(groups)}: {v} mm/s, {a} mm/s2', f'M118 air group {i}: E {v} mm/s accel {a}',
              f'M201 E{a}', f'M204 R{a}']
        for _ in range(8):
            g += [f'G1 E4 F{v * 60}', f'G1 E-4 F{v * 60}']
        g += ['M400', 'G4 S3']
    g += ['M501 ; restore the saved limits', f'G1 E-2 F1800', 'M104 S0', 'M117 Air test done', 'M118 air test done']
    with open(os.path.join(OUT, 'LA0_AIR.gcode'), 'w', newline='\n') as f: f.write('\n'.join(g) + '\n')

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    air_test()
    common = ['Edge pattern: 10 mm at 25 mm/s, 20 mm at 100 mm/s, 10 mm at 25 mm/s; accel = your M204 P.',
              'ElegooSlicer is not involved. LA values are not saved (no M500).']
    ks = [round(0.1 * i, 2) for i in range(0, 13)]
    tower('LA1_K.gcode', 'K tower 0.0 .. 1.2 (J = K, B 0.01, U 0.02)', 'K', ks,
          'M900 J0 B0.01 U0.02 R15 A5000 V0', common + ['Band n (from 1 mm): K = 0.1 x (n-1).'])
    us = [0.01, 0.02, 0.03, 0.05, 0.07, 0.09, 0.11, 0.13, 0.15]
    tower('LA2_U.gcode', 'U tower 0.01 .. 0.15', 'U', us,
          'M900 K0.60 J0 B0.01 R15 A5000 V0', common + ['Set K in the top M900 line to the K tower result first.'])
    js = [0, 0.8, 1.0, 1.2, 1.4, 1.6, 1.8, 2.0]
    tower('LA3_J.gcode', 'J tower 0 (=K) .. 2.0', 'J', js,
          'M900 K0.60 U0.05 B0.01 R15 A5000 V0', common + ['Set K and U in the top M900 line first. J0 = same as K.'])
    print('written to', os.path.abspath(OUT))
